-- DB schema for ResultsService

BEGIN;

CREATE TABLE IF NOT EXISTS site (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    base_url VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS "user" (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(150) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS parse_session (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id INT NOT NULL REFERENCES site(id),
    user_id INT NOT NULL REFERENCES "user"(id),
    status VARCHAR(50) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ NULL,
    processed_items INT NULL
);

CREATE TABLE IF NOT EXISTS product (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id INT NOT NULL REFERENCES site(id),
    external_id VARCHAR(100) NULL,
    name VARCHAR(255) NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    old_price DECIMAL(10,2) NULL,
    currency VARCHAR(3) NOT NULL,
    description TEXT NULL,
    category VARCHAR(100) NULL,
    in_stock BOOLEAN NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS price_history (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT NOT NULL REFERENCES product(id) ON DELETE CASCADE,
    price DECIMAL(10,2) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_product_site_id ON product(site_id);
CREATE INDEX IF NOT EXISTS ix_product_external_id ON product(external_id);
CREATE INDEX IF NOT EXISTS ix_product_category ON product(category);
CREATE INDEX IF NOT EXISTS ix_product_in_stock ON product(in_stock);
CREATE INDEX IF NOT EXISTS ix_price_history_product_id ON price_history(product_id);

COMMIT;
